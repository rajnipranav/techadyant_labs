export interface LoadDossierResult {
  found: boolean;
  dossier: EntityDossier | null;
}

export function loadDossier(slug: string): LoadDossierResult {
  const dossier = DOSSIER_MAP[slug];
  return dossier ? { found: true, dossier } : { found: false, dossier: null };
}

export function listDossierSlugs(): string[] {
  return Object.keys(DOSSIER_MAP);
}

export function listDossiersByVertical(vertical: EntityDossier["vertical"]): EntityDossier[] {
  return Object.values(DOSSIER_MAP).filter((d) => d.vertical === vertical);
}

// Helper: return static params for a route segment that maps to a given base path
export function listStaticParamsForBase(basePath: string): { slug: string }[] {
  return Object.values(DOSSIER_MAP)
    .filter((d) => (d.seo?.canonical_path || d.header?.entity_path || '')?.startsWith(basePath))
    .map((d) => ({ slug: d.slug }));
}